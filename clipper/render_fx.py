#!/usr/bin/env python3
"""Premium Short renderer: frame-by-frame compositing (OpenCV) + mixed SFX (ffmpeg).

- Layout: facecam on top (head-locked: YuNet face tracking, smoothed), gameplay below; vertical face-follow
  crop when there is no facecam.
- Cold-open hook (loudest ~3 s first), then the clip.
- Captions: Anton, ALL CAPS, brand blue with a thick black outline and a hard black drop shadow, 1-3 words at a
  time, popping in with a small overshoot; centred on the cam/gameplay seam.
- Title box at the top.
- Red flash + punch-in on the biggest peak, green flash on the hook -> clip cut.
- SFX (generated by make_sfx.py, original): riser into the cut, whoosh, impact on the peak, hit on each flash.

  python3 render_fx.py --src source.mp4 --peak 40 --out short.mp4 --title "speed walked into the wrong room 💀"
"""
import argparse, json, os, subprocess, sys, tempfile
import numpy as np
import cv2
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import render as rd  # noqa: E402  (probe, transcribe, pick_cut, find_cam, pick_hook, loudness)

W, H, FPS = 1080, 1920, 30
BRAND = (0x59, 0xC4, 0xF8)                       # #59C4F8
FONT = os.path.join(HERE, "fonts", "Anton-Regular.ttf")
YUNET = os.path.join(HERE, "models", "face_detection_yunet_2023mar.onnx")
SFX = {k: os.path.join(HERE, "sfx", f"{k}.wav") for k in ("riser", "whoosh2", "impact", "hit")}


# ---------------------------------------------------------------- captions
def caption_pages(words, segs):
    """Words -> pages of 1-3 words on the OUTPUT timeline. A page ends on punctuation, a pause, or 3 words."""
    pages = []
    t_out = 0.0
    for a, b in segs:
        ws = [w for w in words if w["start"] >= a - 0.05 and w["end"] <= b + 0.05]
        cur = []
        for i, w in enumerate(ws):
            cur.append(w)
            nxt = ws[i + 1] if i + 1 < len(ws) else None
            end_page = (len(cur) == 3 or nxt is None or nxt["start"] - w["end"] > 0.35
                        or w["text"].strip()[-1:] in ".,!?" or len(" ".join(x["text"] for x in cur)) > 14)
            if end_page:
                s = t_out + max(0.0, cur[0]["start"] - a); e = t_out + (min(b, (nxt["start"] if nxt else w["end"] + 0.4)) - a)
                txt = " ".join(x["text"].strip() for x in cur).upper().strip(" .,")
                if txt:
                    pages.append({"s": s, "e": max(e, s + 0.25), "text": txt})
                cur = []
        t_out += b - a
    return pages


def caption_image(text, size=118):
    """Brand-blue Anton text, thick black outline, hard black drop shadow (RGBA)."""
    f = ImageFont.truetype(FONT, size)
    stroke = max(6, int(size * 0.11)); shadow = (int(size * 0.07), int(size * 0.08))
    box = f.getbbox(text, stroke_width=stroke)
    tw, th = box[2] - box[0], box[3] - box[1]
    im = Image.new("RGBA", (tw + shadow[0] + 20, th + shadow[1] + 20), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    x, y = 10 - box[0], 10 - box[1]
    d.text((x + shadow[0], y + shadow[1]), text, font=f, fill=(0, 0, 0, 255), stroke_width=stroke, stroke_fill=(0, 0, 0, 255))
    d.text((x, y), text, font=f, fill=BRAND + (255,), stroke_width=stroke, stroke_fill=(0, 0, 0, 255))
    return np.array(im)


def fit_caption(text):
    for size in (124, 112, 100, 90, 80):
        img = caption_image(text, size)
        if img.shape[1] <= W - 80:
            return img
    return caption_image(text, 72)


def pop_scale(t):
    """0 -> 1.08 -> 1.0 over 0.2 s (snappy overshoot)."""
    if t >= 0.2: return 1.0
    if t < 0.12: return 0.55 + (1.08 - 0.55) * (t / 0.12) ** 0.6
    return 1.08 - 0.08 * ((t - 0.12) / 0.08)


def overlay(frame, rgba, cx, cy, scale=1.0, alpha=1.0):
    if scale != 1.0:
        rgba = cv2.resize(rgba, (max(1, int(rgba.shape[1] * scale)), max(1, int(rgba.shape[0] * scale))), interpolation=cv2.INTER_LINEAR)
    h, w = rgba.shape[:2]
    x0, y0 = int(cx - w / 2), int(cy - h / 2)
    x1, y1 = max(0, x0), max(0, y0); x2, y2 = min(frame.shape[1], x0 + w), min(frame.shape[0], y0 + h)
    if x2 <= x1 or y2 <= y1: return
    sub = rgba[y1 - y0:y2 - y0, x1 - x0:x2 - x0]
    a = (sub[..., 3:4].astype(np.float32) / 255.0) * alpha
    roi = frame[y1:y2, x1:x2].astype(np.float32)
    frame[y1:y2, x1:x2] = (roi * (1 - a) + sub[..., :3][..., ::-1].astype(np.float32) * a).astype(np.uint8)   # RGBA -> BGR


# ---------------------------------------------------------------- face tracking (head lock)
def track_faces(src, segs, region, sw, sh_):
    """Face centre (x, y, size) per output frame inside `region` (x, y, w, h) of the source, smoothed."""
    det = cv2.FaceDetectorYN.create(YUNET, "", (320, 320), 0.6, 0.3, 50)
    rx, ry, rw, rh = region
    scale = 320.0 / max(rw, rh)
    dw, dh = int(rw * scale) // 2 * 2, int(rh * scale) // 2 * 2
    det.setInputSize((dw, dh))
    pts = []
    for a, b in segs:
        raw = subprocess.run(["ffmpeg", "-v", "error", "-ss", f"{a:.3f}", "-to", f"{b:.3f}", "-i", src,
                              "-vf", f"crop={rw}:{rh}:{rx}:{ry},scale={dw}:{dh},fps={FPS}", "-f", "rawvideo", "-pix_fmt", "bgr24", "-"],
                             capture_output=True, check=True).stdout
        n = len(raw) // (dw * dh * 3)
        frames = np.frombuffer(raw[: n * dw * dh * 3], np.uint8).reshape(n, dh, dw, 3)
        for i in range(n):
            if i % 2 == 0:  # detect at 15 fps, hold in between
                _, faces = det.detect(frames[i])
                if faces is not None and len(faces):
                    f = max(faces, key=lambda r: r[2] * r[3])
                    last = (rx + (f[0] + f[2] / 2) / scale, ry + (f[1] + f[3] / 2) / scale, f[2] / scale)
                else:
                    last = pts[-1] if pts and pts[-1] else None
            pts.append(last if i % 2 == 0 else (pts[-1] if pts else None))
    # fill gaps, then smooth hard (critically damped feel): no jitter, still follows head moves
    first = next((p for p in pts if p), (rx + rw / 2, ry + rh / 2, rw / 3))
    out, cur = [], np.array(first, dtype=np.float64)
    for p in pts:
        tgt = np.array(p if p else cur)
        cur = cur + 0.12 * (tgt - cur)
        out.append(cur.copy())
    return out


# ---------------------------------------------------------------- render
def render(src, peak, out, title=None, model="base.en", words=None):
    sw, sh_, dur = rd.probe(src)
    words = words if words is not None else rd.transcribe(src, model)
    start, end = rd.pick_cut(words, peak, dur)
    cam = rd.find_cam(src, sw, sh_, dur)
    hk = rd.pick_hook(src, words, start, end)
    segs = ([hk] if hk else []) + [(start, end)]
    total = sum(b - a for a, b in segs)
    n_frames = int(round(total * FPS))
    cut_t = (hk[1] - hk[0]) if hk else None

    # loudness on the output timeline -> biggest peak (red flash + punch-in + impact)
    loud = np.concatenate([rd.loudness(src, a, b) for a, b in segs])
    pk_i = int(np.argmax(np.convolve(loud, np.ones(5) / 5, "same"))) if len(loud) else 0
    peak_t = pk_i * 0.1
    if cut_t is not None and abs(peak_t - cut_t) < 0.6:
        peak_t = cut_t + 0.6

    split = 0.38; ch = int(H * split) // 2 * 2; gh = H - ch
    if cam and cam[0] != "face":
        bx, by, bw, bh = cam
        # stay a little inside the overlay border so stream counters/alerts touching the cam never show
        ix, iy = int(bw * 0.04), int(bh * 0.07)
        bx, by, bw, bh = bx + ix, by + iy, bw - 2 * ix, bh - 2 * iy
        track = track_faces(src, segs, (bx, by, bw, bh), sw, sh_)
        layout = "cam+game"
    else:
        cw = int(sh_ * W / H)
        track = track_faces(src, segs, (0, 0, sw, sh_), sw, sh_)
        layout = "vertical"

    pages = caption_pages(words, segs)
    page_imgs = [fit_caption(p["text"]) for p in pages]
    tmp = tempfile.mkdtemp()
    title_png = None
    if title:
        tp = os.path.join(tmp, "title.png")
        subprocess.run([sys.executable, os.path.join(HERE, "make_title.py"), title, tp, "150"], check=True, capture_output=True)
        title_png = np.array(Image.open(tp).convert("RGBA"))

    # decode the source for each segment in order, composite each frame, pipe to the encoder
    silent = os.path.join(tmp, "video.mp4")
    enc = subprocess.Popen(["ffmpeg", "-v", "error", "-y", "-f", "rawvideo", "-pix_fmt", "bgr24", "-s", f"{W}x{H}", "-r", str(FPS), "-i", "-",
                            "-c:v", "libx264", "-preset", "medium", "-crf", "17", "-maxrate", "6.4M", "-bufsize", "12M", "-pix_fmt", "yuv420p", silent],
                           stdin=subprocess.PIPE)
    fi = 0
    for a, b in segs:
        dec = subprocess.Popen(["ffmpeg", "-v", "error", "-ss", f"{a:.3f}", "-to", f"{b:.3f}", "-i", src, "-vf", f"fps={FPS}",
                                "-f", "rawvideo", "-pix_fmt", "bgr24", "-"], stdout=subprocess.PIPE)
        fsize = sw * sh_ * 3
        while True:
            buf = dec.stdout.read(fsize)
            if len(buf) < fsize or fi >= n_frames: break
            src_f = np.frombuffer(buf, np.uint8).reshape(sh_, sw, 3)
            t = fi / FPS
            fx, fy, fsz = track[min(fi, len(track) - 1)]
            # punch-in around the biggest peak: 1.0 -> 1.14 in 0.12 s, eases back over 0.7 s
            dz = t - peak_t
            punch = 0.0 if dz < 0 else (0.14 * dz / 0.12 if dz < 0.12 else max(0.0, 0.14 * (1 - (dz - 0.12) / 0.7)))
            frame = np.zeros((H, W, 3), np.uint8)
            if layout == "cam+game":
                # head lock: crop a box of the cam's aspect centred on the face, kept inside the cam overlay
                zoom = 1.12 + punch
                cwid = bw / zoom; chei = cwid * ch / W
                cx0 = min(max(fx - cwid / 2, bx), bx + bw - cwid); cy0 = min(max(fy - chei * 0.45, by), by + bh - chei)
                camc = src_f[int(cy0):int(cy0 + chei), int(cx0):int(cx0 + cwid)]
                frame[:ch] = cv2.resize(camc, (W, ch), interpolation=cv2.INTER_LANCZOS4)
                gw = int(sh_ * W / gh); gx = int(min(max((sw - gw) / 2, 0), sw - gw))
                frame[ch:] = cv2.resize(src_f[:, gx:gx + gw], (W, gh), interpolation=cv2.INTER_AREA)
                cap_y = ch
            else:
                zoom = 1.0 + punch
                cwid = cw / zoom; chei = sh_ / zoom
                cx0 = min(max(fx - cwid / 2, 0), sw - cwid); cy0 = min(max(fy - chei * 0.4, 0), sh_ - chei)
                frame[:] = cv2.resize(src_f[int(cy0):int(cy0 + chei), int(cx0):int(cx0 + cwid)], (W, H), interpolation=cv2.INTER_LANCZOS4)
                cap_y = int(H * 0.66)
            # flashes: green on the hook->clip cut, red on the peak (fast attack, 0.25 s fade)
            for ft, col in ((cut_t, (60, 220, 90)), (peak_t, (40, 40, 235))):
                if ft is None: continue
                d = t - ft
                if 0 <= d < 0.25:
                    a_ = 0.42 * (1 - d / 0.25)
                    frame[:] = (frame.astype(np.float32) * (1 - a_) + np.array(col, np.float32) * a_).astype(np.uint8)
            if title_png is not None:
                overlay(frame, title_png, W / 2, H / 2)
            for p, img in zip(pages, page_imgs):
                if p["s"] <= t < p["e"]:
                    overlay(frame, img, W / 2, cap_y, pop_scale(t - p["s"]))
                    break
            enc.stdin.write(frame.tobytes()); fi += 1
        dec.stdout.close(); dec.wait()
    while fi < n_frames:  # pad if a segment came up a frame short
        enc.stdin.write(frame.tobytes()); fi += 1
    enc.stdin.close(); enc.wait()

    # audio: segments + SFX
    parts = "".join(f"[0:a]atrim={a:.3f}:{b:.3f},asetpts=PTS-STARTPTS[a{i}];" for i, (a, b) in enumerate(segs))
    graph = parts + "".join(f"[a{i}]" for i in range(len(segs))) + f"concat=n={len(segs)}:v=0:a=1[voice];"
    sfx_in, mix = [], ["[voice]"]
    def add(name, at, vol):
        if at is None or at < 0: return
        sfx_in.extend(["-i", SFX[name]]); k = len(sfx_in) // 2
        nonlocal_graph.append(f"[{k}:a]adelay={int(at * 1000)}:all=1,volume={vol}[s{k}];"); mix.append(f"[s{k}]")
    nonlocal_graph = []
    if cut_t is not None:
        add("riser", cut_t - 1.6, 0.45); add("whoosh2", max(0, cut_t - 0.25), 0.6); add("hit", cut_t, 0.5)
    add("impact", peak_t, 0.7); add("hit", peak_t, 0.45)
    graph += "".join(nonlocal_graph) + "".join(mix) + f"amix=inputs={len(mix)}:duration=first:normalize=0,loudnorm=I=-14:TP=-1.5:LRA=11[aout]"
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", src, *sfx_in, "-i", silent, "-filter_complex", graph,
                    "-map", f"{len(sfx_in) // 2 + 1}:v", "-map", "[aout]", "-c:v", "copy", "-c:a", "aac", "-b:a", "192k", "-ar", "48000",
                    "-shortest", "-movflags", "+faststart", out], check=True)
    text = " ".join(w["text"] for w in words if start <= w["start"] <= end)
    return {"start": start, "end": end, "hook": hk, "duration": round(total, 1), "layout": layout, "peak_t": round(peak_t, 2),
            "cut_t": cut_t, "captions": len(pages), "transcript": text}


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--src", required=True); p.add_argument("--peak", type=float, required=True); p.add_argument("--out", required=True)
    p.add_argument("--title"); p.add_argument("--model", default="base.en")
    a = p.parse_args()
    print(json.dumps(render(a.src, a.peak, a.out, a.title, a.model), indent=1, default=str))
